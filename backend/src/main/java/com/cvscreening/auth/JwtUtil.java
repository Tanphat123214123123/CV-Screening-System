package com.cvscreening.auth;

import io.jsonwebtoken.Claims;
import io.jsonwebtoken.JwtException;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.SignatureAlgorithm;
import io.jsonwebtoken.security.Keys;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import javax.crypto.SecretKey;
import java.nio.charset.StandardCharsets;
import java.util.Date;

/** Tao va xac thuc JSON Web Token (HS256). */
@Component
@Slf4j
public class JwtUtil {

    /** Gia tri mac dinh trong application.yml — chi danh cho dev local. */
    private static final String DEFAULT_DEV_SECRET = "cv-screening-secret-key-change-me-in-production-2026";

    private final SecretKey key;
    private final long expirationMs;

    public JwtUtil(@Value("${app.jwt.secret}") String secret,
                   @Value("${app.jwt.expiration-ms}") long expirationMs) {
        if (DEFAULT_DEV_SECRET.equals(secret)) {
            log.warn("!!! JWT_SECRET dang dung gia tri mac dinh cho dev local. "
                    + "TUYET DOI khong deploy production voi secret nay — attacker co the tu ky token voi bat ky role nao. "
                    + "Dat bien moi truong JWT_SECRET (>= 32 ky tu ngau nhien) truoc khi deploy that.");
        }
        this.key = Keys.hmacShaKeyFor(secret.getBytes(StandardCharsets.UTF_8));
        this.expirationMs = expirationMs;
    }

    public String generateToken(String email, String role) {
        Date now = new Date();
        return Jwts.builder()
                .setSubject(email)
                .claim("role", role)
                .setIssuedAt(now)
                .setExpiration(new Date(now.getTime() + expirationMs))
                .signWith(key, SignatureAlgorithm.HS256)
                .compact();
    }

    public String extractEmail(String token) {
        return parseClaims(token).getSubject();
    }

    public boolean isValid(String token) {
        try {
            parseClaims(token);
            return true;
        } catch (JwtException | IllegalArgumentException e) {
            return false;
        }
    }

    private Claims parseClaims(String token) {
        return Jwts.parserBuilder().setSigningKey(key).build()
                .parseClaimsJws(token).getBody();
    }
}
